/**
 * Checks the licence of every library Protégé ships with (production dependencies, all the way down)
 * and writes THIRD-PARTY-NOTICES.md. Fails if one has no licence or one that doesn't fit Protégé's
 * (AGPL-3.0, free and open source, no paid anything).
 *
 *   npm run licenses
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

// licences that are free, open source and fine to ship inside an AGPL-3.0 app
// (LGPL is too: it's the image tool Next.js uses, and LGPL code can live inside AGPL software)
const OK = /^(MIT|ISC|BSD|BSD-2-Clause|BSD-3-Clause|0BSD|Apache-2\.0|BlueOak-1\.0\.0|CC0-1\.0|CC-BY-4\.0|Unlicense|OFL-1\.1|MPL-2\.0|Python-2\.0|Zlib|WTFPL|LGPL-3\.0-or-later)$/;

/** Checked by hand, with the reason (free forever, but not an open-source licence) */
const ALLOWED: Record<string, string> = {
  gsap: "free for everyone forever under GSAP's Standard \"No Charge\" License (not open source); used for Gloam's eureka moment",
};

interface Node {
  version?: string;
  path?: string;
  dependencies?: Record<string, Node>;
}

const tree = JSON.parse(execSync("npm ls --omit=dev --all --json --long", { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })) as Node;
const found = new Map<string, { version: string; license: string; repo?: string }>();
const walk = (n: Node) => {
  for (const [name, dep] of Object.entries(n.dependencies ?? {})) {
    const key = `${name}@${dep.version}`;
    if (found.has(key) || !dep.path) continue;
    const pkg = JSON.parse(fs.readFileSync(path.join(dep.path, "package.json"), "utf8")) as { license?: string | { type: string }; licenses?: { type: string }[]; repository?: string | { url: string } };
    const license = typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? pkg.licenses?.map((l) => l.type).join(" OR ") ?? "UNKNOWN");
    const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
    found.set(key, { version: dep.version ?? "", license, repo });
    walk(dep);
  }
};
walk(tree);

/** "(MIT OR Apache-2.0)" is fine if any choice is fine; "MIT AND BSD" only if all are */
const fine = (expr: string) =>
  expr
    .replace(/[()]/g, "")
    .split(/\s+OR\s+/)
    .some((choice) => choice.split(/\s+AND\s+/).every((l) => OK.test(l.trim())));

const bad = [...found].filter(([k, v]) => !fine(v.license) && !ALLOWED[k.slice(0, k.lastIndexOf("@"))]);
const rows = [...found].sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `| ${k.slice(0, k.lastIndexOf("@"))} | ${v.version} | ${v.license} |`);

const notices = `# Third-party notices

Protégé is free software under the GNU Affero General Public License v3.0 (see LICENSE).
It's built on the free and open-source work below. Thank you to everyone who made it.

## Libraries shipped with Protégé

Generated by \`npm run licenses\`, which checks every licence fits.

| Library | Version | Licence |
|---|---|---|
${rows.join("\n")}

${Object.entries(ALLOWED)
  .map(([name, why]) => `**${name}**: ${why}.`)
  .join("\n")}

## Fonts (SIL Open Font License 1.1)

- Atkinson Hyperlegible Next, by the Braille Institute
- Recursive, by Arrow Type
- Shantell Sans, by Shantell Martin and Arrow Type
- OpenDyslexic, by Abbie Gonzalez

## Downloaded on the teacher's laptop, never shipped inside Protégé

- **Ollama** (MIT) runs the AI model.
- **Qwen3 4B Instruct** (Apache 2.0) is Gloam's default model.
- **whisper.cpp** (MIT), by the ggml authors, runs voice typing.
- **Whisper speech models** (MIT), by OpenAI, converted by the whisper.cpp project.
- **sherpa-onnx** (Apache 2.0), by the k2-fsa project, runs Gloam's read-aloud voice. It includes
  **ONNX Runtime** (MIT, Microsoft) and **espeak-ng** (GPL 3.0) with its language data, which turns French
  text and new English words into sounds.
- **Kokoro-82M** (Apache 2.0), by hexgrad, is Gloam's read-aloud voice, packed for sherpa-onnx.

## Art

The paintings in \`public/art\` were made for Protégé on a local computer with FLUX.1-schnell
(Apache 2.0, by Black Forest Labs) and finished by hand-written scripts in \`art/\`. They're part of
Protégé and shared under the same licence.
`;
fs.writeFileSync("THIRD-PARTY-NOTICES.md", notices);
console.log(`${found.size} libraries checked, THIRD-PARTY-NOTICES.md written.`);
if (bad.length) {
  console.error(`\n${bad.length} need a look:`);
  for (const [k, v] of bad) console.error(`  ${k}: ${v.license}`);
  process.exit(1);
}
